#!/usr/bin/env node
/**
 * Zarządza lokalnym seedem urządzenia (plik src/data/localSeed.ts pozostaje w .gitignore).
 *
 * Przykłady:
 *   node scripts/use-seed.mjs --clear
 *   node scripts/use-seed.mjs --list
 *   node scripts/use-seed.mjs seeds/hubert-rydzyk.json
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');
const SEEDS_DIR = path.join(ROOT, 'seeds');
const TARGET_FILE = path.join(ROOT, 'src', 'data', 'localSeed.ts');
const TEMPLATE_FILE = path.join(ROOT, 'src', 'data', 'localSeed.template.ts');

const args = process.argv.slice(2);
const cmd = args[0];

if (cmd === '--list') {
  if (!fs.existsSync(SEEDS_DIR)) {
    console.log('Katalog seeds/ nie istnieje jeszcze lokalnie.');
    process.exit(0);
  }
  const files = fs.readdirSync(SEEDS_DIR).filter((f) => f.endsWith('.json'));
  if (files.length === 0) {
    console.log('Brak plików *.json w seeds/.');
  } else {
    console.log('Dostępne lokalne seedy w seeds/:');
    for (const file of files) {
      console.log(`  - seeds/${file}`);
    }
  }
  process.exit(0);
}

if (!cmd || cmd === '--clear') {
  if (fs.existsSync(TEMPLATE_FILE)) {
    fs.copyFileSync(TEMPLATE_FILE, TARGET_FILE);
  } else {
    fs.writeFileSync(
      TARGET_FILE,
      `import type { LocalDeviceSeedConfig } from './localSeed.template';\n\nexport const LOCAL_DEVICE_SEED: LocalDeviceSeedConfig | null = null;\n`,
      'utf8'
    );
  }
  console.log('✅ Wyczyszczono src/data/localSeed.ts (LOCAL_DEVICE_SEED = null — czysty onboarding).');
  process.exit(0);
}

const seedPath = path.isAbsolute(cmd) ? cmd : path.join(ROOT, cmd);
if (!fs.existsSync(seedPath)) {
  console.error(`❌ Nie znaleziono pliku seeda: ${seedPath}`);
  process.exit(1);
}

const rawJson = fs.readFileSync(seedPath, 'utf8');
const parsed = JSON.parse(rawJson);
if (!parsed || !parsed.profile || !Array.isArray(parsed.plans)) {
  console.error('❌ Nieprawidłowy format pliku seeda (wymagane profile i plans[]).');
  process.exit(1);
}

const generated = `// AUTO-GENERATED BY scripts/use-seed.mjs FROM ${path.relative(ROOT, seedPath)}
// Ten plik jest w .gitignore i nigdy nie trafia do repozytorium GitHub.
import type { LocalDeviceSeedConfig } from './localSeed.template';

export const LOCAL_DEVICE_SEED: LocalDeviceSeedConfig | null = ${JSON.stringify(parsed, null, 2)};
`;

fs.writeFileSync(TARGET_FILE, generated, 'utf8');
console.log(`✅ Załadowano lokalny seed: ${path.relative(ROOT, seedPath)} -> src/data/localSeed.ts`);
